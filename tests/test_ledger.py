def test_held_conflict_when_the_citing_record_names_a_different_type(tmp_path):
    root = tmp_path
    take_dir = root / ".cache" / "takes" / "efx-params-01-50-heldconflict"
    take_dir.mkdir(parents=True)
    _wav(take_dir, "struck_kit-0-00")
    record_id = _publish(
        root,
        "mismatch.json",
        [
            STAGE,
            ".cache/takes/efx-params-01-50-heldconflict",
            "--type",
            "01 51",
            "--held",
            f"{HELD_ADDR}={HELD_BYTES}",
        ],
        measured_at=MEASURED_AT,
    )

    found = ledger.build(UNIT, root=root)
    entry = found["directories"]["efx-params-01-50-heldconflict"]
    # dirname says 01 50; the citing record's own --type says 01 51, which is
    # itself a citing_record type candidate -- so type is a conflict too, and
    # the held offer is excluded for asserting a type ("01 51") that differs
    # from the directory's (null, because of that very conflict).
    assert entry["type"] is None
    assert entry["type_conflict"] == [
        {"source": "citing_record", "value": "01 51"},
        {"source": "dirname", "value": "01 50"},
    ]
    assert entry["held"] is None
    assert entry["held_from"] is None
    assert entry["held_conflict"] == [
        {
            "record": record_id,
            "source": "citing_invocation",
            "record_type": "01 51",
            "dir_type": None,
        }
    ]


