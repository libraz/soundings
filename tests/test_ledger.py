    conflicted.mkdir(parents=True)
    _wav(conflicted, "struck_kit-0-00")
    (conflicted / "takes-manifest.json").write_text(json.dumps({"type": "03 01"}))

    found = ledger.build(UNIT, root=root)
    assert set(found["directories"]) == {"plain", "efx-params-02-0a", "efx-params-03-00-x"}
    for entry in found["directories"].values():
        if entry["type"] is not None:
            assert entry["type_conflict"] is None
        elif entry["type_conflict"] is not None:
            assert len(entry["type_conflict"]) >= 2
        # else: type is null with no source at all, which is the third
        # allowed state -- nothing here is silently dropped.


